from pathlib import Path
import json,re,sys,html
root=Path(__file__).resolve().parents[1]
def read(n):return (root/n).read_text()
def plain(s):return ' '.join(html.unescape(re.sub(r'<[^>]+>',' ',s)).split())
def link(title,href,kind):return dict(title=title,href=href,kind=kind)
pages=[link('Главная','index.html','Страница'),link('Детям','detyam.html','Страница'),link('Услуги','uslugi.html','Страница'),link('Лечение во сне и седация','lechenie-vo-sne.html','Страница'),link('Врачи','doctors.html','Страница'),link('Цены','uslugi-i-ceny.html','Страница'),link('Отзывы','reviews.html','Страница'),link('О клинике','index.html#about','Страница'),link('Контакты','contacts.html','Страница'),link('Налоговый вычет','nalogovyy-vychet.html','Страница'),link('Документы и лицензия','documents.html','Страница'),link('Карта сайта','sitemap.html','Страница')]
services=json.loads(read('data/services.json'))['services'];service_links=[link(s['title'],s['slug'],'Услуга') for s in services]
files=sorted((root/'data/doctors').glob('*.json'));doctors=[json.loads(p.read_text()) for p in files];doctors.sort(key=lambda d:d['order']);doctor_links=[link(d['name'],'doctor-'+d['id']+'.html','Врач') for d in doctors if d['publication']['catalog']]
prices=[]
for section in re.finditer(r'<section class="prices-category" id="([^"]+)"[\s\S]*?</section>',read('dist/uslugi-i-ceny.html')):
 for title in re.findall(r'<dt>([\s\S]*?)</dt>',section.group()):
  title=plain(title)
  if title:prices.append(link(title,'uslugi-i-ceny.html#'+section.group(1),'Цена'))
index=pages+service_links+doctor_links+prices
assert len(doctor_links)>0 and len(prices)>0
indexjs='// Generated by scripts/generate-search.py.\nwindow.METELITSA_SEARCH_INDEX = '+json.dumps(index,ensure_ascii=False,separators=(',',':')).replace('</','<\\/')+';\n'
template=read('templates/sitemap.html')
def listing(items):return '\n'.join('<li><a href="'+html.escape(i['href'],quote=True)+'">'+html.escape(i['title'])+'</a></li>' for i in items if i['href']!='sitemap.html')
values={'PAGES':listing(pages),'SERVICES':listing(service_links),'DOCTORS':listing(doctor_links)}
for k,v in values.items():template=template.replace('{{'+k+'}}',v)
assert '{{' not in template
outputs={'dist/search-index.js':indexjs,'dist/sitemap.html':template}
check='--check' in sys.argv
for name,content in outputs.items():
 p=root/name
 if check:assert p.exists() and p.read_text()==content, 'Regenerate '+name
 else:p.write_text(content)
print(('Verified' if check else 'Generated')+f' search and sitemap: {len(index)} entries, {len(doctor_links)} doctors, {len(prices)} prices.')
