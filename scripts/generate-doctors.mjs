const root = path.resolve(import.meta.dirname, '..');
const dist = path.join(root, 'dist');
const marker = '<!-- Generated by scripts/generate-doctors.mjs.';
export const filterLabels = {
  all: 'Все врачи', therapy: 'Терапевты', surgery: 'Хирурги', children: 'Детские стоматологи',
  chief: 'Главный врач', general: 'Стоматологи общей практики', orthopedics: 'Ортопеды',
  orthodontics: 'Ортодонты', endodontics: 'Эндодонтия', prevention: 'Гигиенисты',
  anesthesia: 'Анестезиологи',
};
export const escapeHtml = value => String(value).replace(/[&<>"']/g, c => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
}[c]));
export const yearWord = n => n % 10 === 1 && n % 100 !== 11 ? 'год'
  : n % 10 >= 2 && n % 10 <= 4 && (n % 100 < 12 || n % 100 > 14) ? 'года' : 'лет';
const text = (value, label) => assert.ok(typeof value === 'string' && value.trim(), `Missing text: ${label}`);
const date = value => /^\d{4}-\d{2}-\d{2}$/.test(value) && !Number.isNaN(Date.parse(value));
const reviewSources = new Map([
  ['yandex', { title: 'Яндекс', host: 'yandex.ru' }],
  ['32top', { title: '32top', host: 'www.32top.ru' }],
  ['startsmile', { title: 'Startsmile', host: 'spb.startsmile.ru' }],
]);
const reviewDate = new Intl.DateTimeFormat('ru-RU', { dateStyle: 'long', timeZone: 'UTC' });
const homepageReviewsSlot = /(^[ \t]*<!-- imported-reviews:start -->\n)[\s\S]*?(^[ \t]*<!-- imported-reviews:end -->)/m;
const homepageDoctorsSlot = /(^[ \t]*<!-- generated-doctors:start -->\n)[\s\S]*?(^[ \t]*<!-- generated-doctors:end -->)/m;

export function readImportedReviews(snapshot) {
  const bySubject = new Map();
  if (snapshot?.version !== 2) return bySubject;
  for (const [key, cards] of Object.entries(snapshot.sources ?? {})) {
    const [provider, subject] = key.split(':');
    const source = reviewSources.get(provider);
    if (!source || !subject || !Array.isArray(cards)) continue;
    const reviews = bySubject.get(subject) ?? new Map();
    for (const card of cards) {
      if (typeof card?.url !== 'string' || typeof card.date !== 'string' || !date(card.date)
        || typeof card.excerpt !== 'string' || !card.excerpt.trim() || card.excerpt.length > 480) continue;
      const url = URL.parse(card.url);
      if (url?.protocol !== 'https:' || url.host !== source.host || url.username || url.password) continue;
      let directLink;
      if (provider === 'yandex') {
        directLink = url.pathname === '/maps/org/metelitsa/1132881772/reviews/'
          && /^[a-z0-9]{15,40}$/.test(url.searchParams.get('reviews[publicId]') ?? '');
      } else if (provider === '32top') {
        directLink = subject === 'clinic' && url.pathname === '/spb/clinics/3886/comments/' && /^#comment_[0-9]+$/.test(url.hash);
      } else {
        const startsmilePath = subject === 'clinic' ? /^\/stomatologii\/metelitsa-otzyvy\.html$/ : /^\/stomatologi\/[a-z0-9_-]+\.html$/;
        directLink = startsmilePath.test(url.pathname) && /^#review[0-9]+$/.test(url.hash);
      }
      if (directLink) reviews.set(url.href, {
        url: url.href, date: card.date, excerpt: card.excerpt, source: source.title,
        author: typeof card.author === 'string' ? card.author.trim() : '',
        text: typeof card.text === 'string' ? card.text.trim() : '',
        clinicReview: provider === 'yandex' && subject !== 'clinic',
      });
    }
    bySubject.set(subject, reviews);
  }
  return new Map([...bySubject].map(([subject, cards]) => [
    subject, [...cards.values()].sort((a, b) => b.date.localeCompare(a.date)),
  ]));
}

export function renderImportedReview(card) {
  const escapeReviewText = value => escapeHtml(value).replace(/\{/g, '&#123;').replace(/\}/g, '&#125;');
  const fullText = card.text ? `\n          <template data-review-text>${escapeReviewText(card.text)}</template>` : '';
  return `<article class="review-card review-card--imported"${card.clinicReview ? ' data-clinic-review' : ''}>
          <h3>${escapeReviewText(card.author || 'Автор не указан')}</h3>
          <p>${escapeReviewText(card.excerpt)}</p>
          <div class="review-meta">
            <time datetime="${card.date}">${reviewDate.format(new Date(card.date))}</time>
            <a class="text-link" href="${escapeHtml(card.url)}" target="_blank" rel="noopener">${escapeHtml(card.source)}</a>
          </div>${fullText}
        </article>`;
}

export function updateHomepageReviews(html, cards) {
  const rendered = cards.map(renderImportedReview).join('\n        ');
  return html.replace(homepageReviewsSlot, (_, start, end) => start + (rendered ? `        ${rendered}\n` : '') + end);
}

function assetPath(value) {
  assert.match(value, /^assets\/doctors\/(?:[a-z0-9-]+\/)*[a-zA-Z0-9_.-]+\.(?:png|jpe?g|webp|svg|pdf)$/);
  assert.ok(!value.split('/').some(part => part === '..' || part === '.'), 'Unsafe asset path');
  assert.ok(fs.existsSync(path.join(dist, value)), `Missing asset: ${value}`);
}

export function validateDoctor(d) {
  assert.equal(d.schemaVersion, 1);
  assert.match(d.id, /^[a-z][a-z0-9-]*$/);
  assert.ok(Number.isInteger(d.order) && d.order > 0, 'Invalid doctor order');
  text(d.name, 'name');
  assert.ok(Array.isArray(d.aliases) && d.aliases.every(s => typeof s === 'string'));
  assert.ok(d.specialties.length > 0); d.specialties.forEach(s => text(s, 'specialty'));
  assert.ok(d.filterTags.every(s => s !== 'all' && Object.hasOwn(filterLabels, s)), 'Unknown filter tag');
  assert.equal(typeof d.publication.catalog, 'boolean');
  assert.equal(typeof d.publication.bookable, 'boolean');
  assert.ok(d.publication.catalog || !d.publication.bookable, 'Unconfirmed catalogue entry cannot be bookable');
  if (d.availabilityLabel !== null) text(d.availabilityLabel, 'availability');
  assert.ok(d.sources && Object.keys(d.sources).length, 'Sources required');
  for (const source of Object.values(d.sources)) {
    text(source.label, 'source label'); text(source.kind, 'source kind');
    const url = new URL(source.url);
    assert.equal(url.protocol, 'https:', 'Sources must use HTTPS');
    assert.ok(!url.username && !url.password, 'Source credentials are forbidden');
    assert.ok(date(source.checkedAt), 'Invalid source check date');
  }
  // Validate references in deferred content too; the renderer never reads that content.
  function refs(value) {
    if (!value || typeof value !== 'object') return;
    for (const [key, item] of Object.entries(value)) {
      if (key === 'sourceRef') assert.ok(Object.hasOwn(d.sources, item), `Unknown source: ${item}`);
      else if (key === 'sourceRefs') {
        assert.ok(Array.isArray(item) && item.length > 0, 'Fact must have a source');
        item.forEach(id => assert.ok(Object.hasOwn(d.sources, id), `Unknown source: ${id}`));
      } else refs(item);
    }
  }
  refs(d);
  const fact = item => assert.ok(Array.isArray(item.sourceRefs) && item.sourceRefs.length, 'Unsourced fact');
  d.about.forEach(p => { text(p.text, 'about'); fact(p); });
  d.education.forEach(item => {
    assert.ok(Number.isInteger(item.year) && item.year >= 1900 && item.year <= 2100, 'Invalid education year');
    text(item.text, 'education'); fact(item);
  });
  if (d.experience) {
    assert.ok(Number.isInteger(d.experience.years) && d.experience.years >= 0 && d.experience.years < 100);
    assert.ok(date(d.experience.asOf)); fact(d.experience);
  }
  d.directions.forEach(group => {
    text(group.title, 'direction'); fact(group);
    assert.ok(group.items.length);
    group.items.forEach(item => {
      text(item.label, 'service'); fact(item);
      assert.ok(['consultation', 'procedure', 'method'].includes(item.kind), 'Direction item needs an explicit kind');
      if (item.kind !== 'consultation') {
        assert.ok(item.sourceRefs.some(id => !['official_staff', 'official_document', 'review_platform'].includes(d.sources[id].kind)),
          'A clinical procedure needs an individual professional source, not a job title, diploma or patient review');
      }
      assert.match(item.href, /^[a-z0-9-]+\.html#[a-z0-9-]+$/, 'Service link must target a local section');
    });
  });
  assert.ok(Array.isArray(d.reviews.links));
  d.reviews.links.forEach(item => {
    assert.equal(d.sources[item.sourceRef]?.kind, 'review_platform', 'Review link must reference a review platform');
  });
  if (d.photo) {
    assetPath(d.photo.path); text(d.photo.alt, 'photo alt');
    assert.ok(Number.isInteger(d.photo.width) && d.photo.width > 0);
    assert.ok(Number.isInteger(d.photo.height) && d.photo.height > 0);
  }
  d.documents.forEach(document => { assetPath(document.path); text(document.title, 'document'); fact(document); });
  return d;
}

export function loadDoctors() {
  const directory = path.join(root, 'data/doctors');
  const records = fs.readdirSync(directory).filter(f => f.endsWith('.json')).map(file => {
    const d = validateDoctor(JSON.parse(fs.readFileSync(path.join(directory, file), 'utf8')));
    assert.equal(file, `${d.id}.json`, 'Filename must match doctor id');
    return d;
  }).sort((a, b) => a.order - b.order);
  for (const field of ['id', 'order', 'name']) {
    assert.equal(new Set(records.map(d => d[field])).size, records.length, `Duplicate ${field}`);
  }
  const names = records.flatMap(d => [d.name, ...d.aliases]);
  assert.equal(new Set(names).size, names.length, 'Duplicate doctor alias');
  return records;
}

function fill(template, values) {
  const result = template.replace(/\{\{(\w+)\}\}/g, (_, key) => {
    assert.ok(Object.hasOwn(values, key), `Unknown template token: ${key}`);
    return values[key];
  });
  assert.doesNotMatch(result, /\{\{\w+\}\}/, 'Unresolved template token');
  return result.replace(/[\t ]+$/gm, '');
}
function portrait(d, context) {
  const photo = d.photo || { path: 'assets/doctors/placeholder.svg', alt: '', width: 1594, height: 1594 };
  const alt = context === 'appointment' ? '' : context === 'card' && d.photo ? previewName(d) : photo.alt;
  const source = d.photo ? photo.path : `${photo.path}?v=20261125`;
  return `<img class="cover" src="${escapeHtml(source)}" width="${photo.width}" height="${photo.height}" alt="${escapeHtml(alt)}" ${context === 'hero' ? 'fetchpriority="high"' : 'loading="lazy"'} draggable="false">`;
}
export function previewName(d) {
  return d.name.trim().split(/\s+/).slice(0, 2).join(' ');
}
const specialtyLabels = new Map([
  ['Главный врач', 'Главный врач'], ['Врач-стоматолог детский', 'Детский стоматолог'],
  ['Врач-стоматолог-терапевт', 'Терапевт'], ['Врач-стоматолог-хирург', 'Хирург'],
  ['Врач-стоматолог-ортопед', 'Ортопед'], ['Врач-ортодонт', 'Ортодонт'],
  ['Врач-стоматолог', 'Стоматолог'], ['Гигиенист стоматологический', 'Гигиенист'],
  ['Врач-анестезиолог-реаниматолог', 'Анестезиолог-реаниматолог'],
]);
function specialty(d) {
  const labels = [...new Set(d.specialties.map(s => specialtyLabels.get(s) || s))];
  const specific = labels.filter(s => labels.length === 1 || s !== 'Стоматолог');
  return specific.join(', ').toLocaleLowerCase('ru');
}
function experience(d, className = '') {
  return d.experience ? `<p${className ? ` class="${className}"` : ''}>опыт: ${d.experience.years} ${yearWord(d.experience.years)}</p>` : '';
}
function about(d) {
  return d.about.length ? `<section class="doctor-about" id="doctor-about" aria-labelledby="doctor-about-title">
          <h2 id="doctor-about-title">О враче</h2>
          ${d.about.map(p => `<p>${escapeHtml(p.text)}</p>`).join('\n          ')}
        </section>` : '';
}
function education(d) {
  return d.education.length ? `<section class="section doctor-education" id="education" aria-labelledby="education-title">
          <h2 id="education-title">Образование</h2>
          <dl>
            ${d.education.map(e => `<div><dt>${e.year}</dt><dd>${escapeHtml(e.text)}</dd></div>`).join('\n            ')}
          </dl>
        </section>` : '';
}
function directions(d) {
  // Keep consultations in the data, but do not present them as clinical scope.
  const groups = d.directions.map(group => ({ ...group, items: group.items.filter(item => item.kind !== 'consultation') }))
    .filter(group => group.items.length);
  return groups.length ? `<section class="section faq doctor-directions" id="directions" aria-labelledby="directions-title">
          <h2 id="directions-title">Направления работы</h2>
          <div class="faq-list">
            ${groups.map(g => `<details name="doctor-directions">
              <summary><span class="doctor-direction-label">${escapeHtml(g.title)}</span><span class="doctor-direction-icon" aria-hidden="true"><img class="doctor-direction-down" src="assets/doctor-direction-down.svg" width="21" height="13" alt=""><img class="doctor-direction-up" src="assets/doctor-direction-up.svg" width="21" height="13" alt=""></span></summary>
              <ul class="doctor-service-links">
                ${g.items.map(item => `<li><a href="${escapeHtml(item.href)}">${escapeHtml(item.label)}</a></li>`).join('\n                ')}
              </ul>
            </details>`).join('\n            ')}
          </div>
        </section>` : '';
}
function reviews(d, imported) {
  const sources = d.reviews.links.map(({ sourceRef }) => d.sources[sourceRef]);
  const cards = imported.length ? imported.map(renderImportedReview) : sources.map(s => `<article class="review-card">
          <h3>${escapeHtml(s.label)}</h3>
          <p>Отзывы о враче: ${escapeHtml(d.name)}.</p>
          <div class="review-meta"><a class="text-link" href="${escapeHtml(s.url)}" target="_blank" rel="noopener">Читать на ${escapeHtml(s.label)}</a></div>
        </article>`);
  if (!cards.length) return '';
  const controls = cards.length > 1 ? `<div class="carousel-controls">
          <button class="icon-button" type="button" data-prev aria-label="${imported.length ? 'Предыдущий отзыв' : 'Предыдущий источник отзывов'}" aria-controls="reviews-track"><img src="assets/carousel-prev.svg" alt=""></button>
          <button class="icon-button" type="button" data-next aria-label="${imported.length ? 'Следующий отзыв' : 'Следующий источник отзывов'}" aria-controls="reviews-track"><img src="assets/carousel-next.svg" alt=""></button>
        </div>` : '';
  const sourceLinks = imported.length && sources.length
    ? '\n      ' + sources.map(s => `<a class="text-link deck-more" href="${escapeHtml(s.url)}" target="_blank" rel="noopener">Все отзывы на ${escapeHtml(s.label)}</a>`).join('\n      ')
    : '';
  return `<section class="section deck doctor-shell doctor-reviews" id="reviews" aria-labelledby="reviews-title"${controls ? ' data-carousel' : ''}>
      <div class="section-heading">
        <h2 id="reviews-title">Отзывы о враче</h2>
        ${controls}
      </div>
      <div class="carousel review-track" id="reviews-track" tabindex="0" aria-label="${imported.length ? 'Карточки отзывов о враче' : 'Источники отзывов о враче'}">
        ${cards.join('\n        ')}
      </div>${sourceLinks}
    </section>`;
}

export function renderDoctor(d, template, imported = []) {
  const reviewSection = reviews(d, imported);
  const rendered = fill(template, {
    name: escapeHtml(d.name), description: escapeHtml(`${d.name}. ${specialty(d)}. Образование и информация о враче стоматологии «Метелица».`),
    specialty: `<p>${escapeHtml(specialty(d))}</p>${experience(d)}${d.availabilityLabel ? `<p>${escapeHtml(d.availabilityLabel)}</p>` : ''}`,
    bookingSubject: d.publication.bookable ? escapeHtml(d.name) : '',
    bookingLabel: d.publication.bookable ? 'записаться к врачу' : 'связаться с клиникой',
    appointmentTitle: d.publication.bookable ? 'Запись на приём' : 'Связаться с клиникой',
    heroPortrait: portrait(d, 'hero'), appointmentPortrait: portrait(d, 'appointment'),
    about: about(d), education: education(d), directions: directions(d), reviews: reviewSection,
  });
  return reviewSection ? rendered : rendered.replaceAll('href="#reviews"', 'href="reviews.html"');
}

export function renderCard(d) {
  const url = `doctor-${d.id}.html`;
  const label = d.publication.bookable ? 'записаться к врачу' : 'о враче';
  const name = escapeHtml(previewName(d));
  return `        <article class="doctor-card" id="doctor-${d.id}" data-doctor-specialties="${d.filterTags.join(' ')}" aria-labelledby="${d.id}-name">
          <div class="doctor-photo">
            <a class="doctor-profile-photo" href="${url}" aria-label="Открыть страницу врача: ${name}">${portrait(d, 'card')}</a>
            <a class="button doctor-book" href="${url}${d.publication.bookable ? '#appointment' : ''}" aria-label="${escapeHtml(label)}: ${name}"><span class="button-label">${label}</span></a>
          </div>
          <h3 id="${d.id}-name"><a class="doctor-profile-link" href="${url}">${name}</a></h3>
          <p>${escapeHtml(specialty(d))}</p>
          ${experience(d, 'doctor-experience')}
          ${d.availabilityLabel ? `<p>${escapeHtml(d.availabilityLabel)}</p>` : ''}
        </article>`;
}
export function renderCatalog(doctors, template) {
  const listed = doctors.filter(d => d.publication.catalog);
  return fill(template, {
    filters: Object.entries(filterLabels).filter(([key]) => key === 'all' || listed.some(d => d.filterTags.includes(key)))
      .map(([key, label]) => `          <button type="button" class="catalog-filter" data-specialty="${key}" aria-pressed="${key === 'all'}" aria-controls="doctors-grid">${label}</button>`).join('\n'),
    catalogStatus: `Показано специалистов: ${listed.length}`,
    cards: listed.map(renderCard).join('\n'),
  });
}

export function updateHomepageDoctors(html, doctors) {
  assert.match(html, homepageDoctorsSlot, 'Homepage doctor slot is missing');
  const cards = doctors.filter(d => d.publication.catalog).map(renderCard).join('\n').replace(/[\t ]+$/gm, '');
  return html.replace(homepageDoctorsSlot, (_, start, end) => start + (cards ? cards + '\n' : '') + end);
}

// Existing carousels keep their layout and IDs, and share the catalogue's labels.
export function updateRelatedCards(html, doctors) {
  return html.replace(/<article\b[^>]*class="[^"]*\bdoctor-card\b[^"]*"[\s\S]*?<\/article>/g, card => {
    const heading = card.match(/<h3\b[^>]*>([\s\S]*?)<\/h3>/)?.[1].replace(/<[^>]+>/g, '').trim();
    const d = doctors.find(d => d.name === heading || previewName(d) === heading || d.aliases.includes(heading));
    if (!d) return card;
    const url = `doctor-${d.id}.html`;
    let result = card.replace(/href="doctor-[a-z0-9-]+\.html(?:#[^"]*)?"/g, `href="${url}"`);
    result = result.replace(/<p class="doctor-experience">[\s\S]*?<\/p>/, experience(d, 'doctor-experience'));
    result = result.replace(/<img\b[^>]*class="cover"[^>]*>/, portrait(d, 'card'));
    result = result.replace(/(<h3\b[^>]*>)([\s\S]*?)(<\/h3>)/, (_, open, content, close) => {
      const name = escapeHtml(previewName(d));
      return open + (content.includes('<a ') ? content.replace(/(<a\b[^>]*>)[\s\S]*?(<\/a>)/, `$1${name}$2`) : name) + close;
    });
    const missingExperience = d.experience && !result.includes('class="doctor-experience"');
    result = result.replace(/(<\/h3>)(\s*)<p>[\s\S]*?<\/p>/, (_, headingEnd, spacing) =>
      `${headingEnd}${spacing}<p>${escapeHtml(specialty(d))}</p>${missingExperience ? spacing + experience(d, 'doctor-experience') : ''}`);
    result = result.replace(/(aria-label="[^"\n]*: )[^"\n]*(")/g, `$1${escapeHtml(previewName(d))}$2`);
    return result.replace(/[\t ]+$/gm, '');
  });
}

export function generate({ check = false } = {}) {
  const doctors = loadDoctors();
  const snapshot = path.join(dist, 'reviews.json');
  const imported = readImportedReviews(fs.existsSync(snapshot) ? JSON.parse(fs.readFileSync(snapshot, 'utf8')) : null);
  const doctorTemplate = fs.readFileSync(path.join(root, 'templates/doctor.html'), 'utf8');
  const catalogTemplate = fs.readFileSync(path.join(root, 'templates/doctors.html'), 'utf8');
  const outputs = new Map(doctors.map(d => [`doctor-${d.id}.html`, renderDoctor(d, doctorTemplate, imported.get(d.id))]));
  outputs.set('doctors.html', renderCatalog(doctors, catalogTemplate));
  const stale = [];
  for (const file of fs.readdirSync(dist).filter(f => f.endsWith('.html'))) {
    if (outputs.has(file)) continue;
    const html = fs.readFileSync(path.join(dist, file), 'utf8');
    if (file.startsWith('doctor-') && html.includes(marker)) {
      stale.push(file);
      if (!check) fs.unlinkSync(path.join(dist, file));
    } else {
      let updated = updateRelatedCards(html, doctors);
      if (file === 'index.html') {
        updated = updateHomepageDoctors(updated, doctors);
        updated = updateHomepageReviews(updated, imported.get('clinic') ?? []);
      }
      if (updated !== html) outputs.set(file, updated);
    }
  }
  for (const [file, content] of outputs) {
    const target = path.join(dist, file);
    const old = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
    if (old === content) continue;
    stale.push(file);
    if (!check) fs.writeFileSync(target, content);
  }
  if (check) assert.equal(stale.length, 0, `Generated files are stale; run npm run build: ${stale.join(', ')}`);
  console.log(`${check ? 'Verified' : 'Generated'} ${doctors.length} doctor pages and ${doctors.filter(d => d.publication.catalog).length} catalogue entries.`);
}
if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  assert.ok(process.argv.slice(2).every(arg => arg === '--check'), 'Supported option: --check');
  generate({ check: process.argv.includes('--check') });
}
